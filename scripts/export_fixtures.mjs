#!/usr/bin/env node
// Exports the Firestore fixtures (firebase/rules-tests/test/fixtureData.js) to
// shared/fixtures/firestore_documents.json, the one test-data source of the rules tests and the
// web's Dart tests. The JSON is committed.
//
//   node scripts/export_fixtures.mjs           write the JSON
//   node scripts/export_fixtures.mjs --check   fail when the committed JSON is out of date (CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { fixtureData } from '../firebase/rules-tests/test/fixtureData.js';

const target = fileURLToPath(new URL('../shared/fixtures/firestore_documents.json', import.meta.url));
const json = `${JSON.stringify(
  {
    $comment:
      'Generated by scripts/export_fixtures.mjs from firebase/rules-tests/test/fixtureData.js: do not edit by hand. ' +
      'Placeholders: {"$serverTimestamp": true} = the server time; {"$arg": "name"} = a builder argument.',
    ...fixtureData,
  },
  null,
  2,
)}\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // missing: out of date
  }
  if (current !== json) {
    console.error(`${target} is out of date: run node scripts/export_fixtures.mjs`);
    process.exit(1);
  }
  console.log('shared/fixtures/firestore_documents.json is up to date');
} else {
  writeFileSync(target, json);
  console.log(`Wrote ${target}`);
}
